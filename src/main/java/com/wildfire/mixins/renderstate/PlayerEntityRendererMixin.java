package com.wildfire.mixins.renderstate;

import com.wildfire.main.entitydata.EntityConfig;
import com.wildfire.main.entitydata.PlayerConfig;
import net.minecraft.client.network.AbstractClientPlayerEntity;
import net.minecraft.client.render.entity.PlayerEntityRenderer;
import net.minecraft.client.render.entity.state.PlayerEntityRenderState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(PlayerEntityRenderer.class)
abstract class PlayerEntityRendererMixin {
	@Inject(method = "updateRenderState(Lnet/minecraft/client/network/AbstractClientPlayerEntity;Lnet/minecraft/client/render/entity/state/PlayerEntityRenderState;F)V", at = @At("TAIL"))
	public void wildfiregender$updatePlayerScale(AbstractClientPlayerEntity entity, PlayerEntityRenderState state, float delta, CallbackInfo ci) {
		var config = EntityConfig.getEntity(entity);
		if(config instanceof PlayerConfig playerConfig) {
			state.baseScale += playerConfig.getScale() - 1;
		}
	}
}
